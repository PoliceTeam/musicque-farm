import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

/** Preserve source artwork; build smaller delivery images with stable content hashes. */
export async function buildMapAssets(app) {
  const require = createRequire(path.join(app, 'package.json'));
  const sharp = require('sharp');
  const output = path.join(app, 'public/chibi-assets/map');
  await mkdir(output, { recursive: true });
  const assets = {};
  for (const [file, options] of [
    ['world-map.jpg', { quality: 85 }],
    ['world-map-sky-clean.png', { quality: 85 }],
    ['world-map-clouds-v3.png', { lossless: true }],
  ]) {
    const source = await readFile(path.join(app, 'src/assets/map', file));
    const image = await sharp(source).webp(options).toBuffer();
    const version = createHash('sha256').update(image).digest('hex').slice(0, 12);
    const name = file.replace(/\.[^.]+$/, `-${version}.webp`);
    await writeFile(path.join(output, name), image);
    const metadata = await sharp(image).metadata();
    assets[file] = { src: `/chibi-assets/map/${name}?v=${version}`, width: metadata.width, height: metadata.height };
  }
  const metadata = { ...JSON.parse(await readFile(path.join(app, 'src/assets/map/sprites.json'), 'utf8')),
    ...JSON.parse(await readFile(path.join(app, 'src/assets/map/world-map-landmarks.json'), 'utf8')) };
  const life = JSON.parse(await readFile(path.join(app, 'src/assets/map/world-map-life.json'), 'utf8'));
  const names = [...new Set([...Object.keys(metadata), ...life.map(entry => entry.id)])]
    .filter(name => !name.startsWith('label-') && !['windmill', 'ferris-wheel', 'ferris-legs', 'plane'].includes(name)).sort();
  const frames = {}, layers = [];
  const width = 1024;
  let x = 2, y = 2, rowHeight = 0;
  for (const name of names) {
    const input = await readFile(path.join(app, 'src/assets/map/sprites', `${name}.png`));
    const size = await sharp(input).metadata();
    if (size.width + 4 > width) throw new Error(`Map sprite too wide: ${name}`);
    if (x + size.width + 2 > width) { x = 2; y += rowHeight + 4; rowHeight = 0; }
    frames[name] = { frame: { x, y, w: size.width, h: size.height }, rotated: false, trimmed: false,
      sourceSize: { w: size.width, h: size.height }, spriteSourceSize: { x: 0, y: 0, w: size.width, h: size.height } };
    layers.push({ input, left: x, top: y });
    x += size.width + 4;
    rowHeight = Math.max(rowHeight, size.height);
  }
  const atlas = await sharp({ create: { width, height: y + rowHeight + 2, channels: 4, background: '#00000000' } })
    .composite(layers).webp({ lossless: true }).toBuffer();
  const version = createHash('sha256').update(atlas).digest('hex').slice(0, 12);
  const name = `world-map-sprites-${version}.webp`;
  await writeFile(path.join(output, name), atlas);
  const spriteAtlas = { url: `/chibi-assets/map/${name}?v=${version}`, data: { frames } };
  await writeFile(path.join(app, 'src/assets/generated-map-assets.ts'),
    `// Generated by tools/runtime/build-map-assets.mjs.\nimport { publicPath } from '@/application/_utils/public-path';\nconst rawMapDeliveryAssets = ${JSON.stringify(assets)};\nexport const mapDeliveryAssets = Object.fromEntries(Object.entries(rawMapDeliveryAssets).map(([key, asset]) => [key, {...asset, src: publicPath(asset.src)}]));\nconst rawMapSpriteAtlas = ${JSON.stringify(spriteAtlas)};\nexport const mapSpriteAtlas = {...rawMapSpriteAtlas, url: publicPath(rawMapSpriteAtlas.url)};\n`);
}
